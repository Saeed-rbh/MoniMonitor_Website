const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'portfolio-currency-'));
process.env.MONIMONITOR_DB_PATH = path.join(directory, 'test.sqlite');
const service = require('./dbService');
let db;
test.before(async () => {
    db = await service.getDb();
    await service.createUser('test', 'test', 'unused');
});
test.after(async () => { await db.close(); fs.rmSync(directory, { recursive: true, force: true }); });
test('empty, single and mixed currency portfolios never combine currencies', async () => {
    const empty = await service.getPortfolioSummary('test');
    assert.deepEqual(empty.totalsByCurrency, []);
    assert.equal(empty.totalValueMinor, 0);
    await service.createInvestmentAccount('test', { name: 'CAD', accountType: 'Savings', currency: 'CAD', cashMinor: 10000 });
    const single = await service.getPortfolioSummary('test');
    assert.equal(single.currency, 'CAD');
    assert.equal(single.totalValueMinor, 10000);
    await service.createInvestmentAccount('test', { name: 'USD', accountType: 'Savings', currency: 'USD', cashMinor: 10000 });
    const card = await service.createInvestmentAccount('test', { name: 'Card', accountType: 'Credit Card', currency: 'CAD', cashMinor: 2000 });
    const broker = await service.createInvestmentAccount('test', { name: 'Broker', accountType: 'TFSA', currency: 'USD', cashMinor: 0 });
    await service.upsertInvestmentHolding('test', broker.id, { symbol: 'TEST', quantity: 2, averageCostMinor: 100, priceMinor: 150, currency: 'USD' });
    const mixed = await service.getPortfolioSummary('test');
    assert.equal(mixed.currency, null);
    for (const key of ['totalValueMinor', 'totalCashMinor', 'totalLiabilitiesMinor', 'holdingsValueMinor', 'holdingsCostMinor', 'gainLossMinor']) assert.equal(mixed[key], null);
    const [cad, usd] = mixed.totalsByCurrency;
    assert.equal(cad.currency, 'CAD');
    assert.equal(cad.totalValueMinor, 8000);
    assert.equal(cad.totalCashMinor, 10000);
    assert.equal(cad.totalLiabilitiesMinor, 2000);
    assert.equal(usd.currency, 'USD');
    assert.equal(usd.totalValueMinor, 10300);
    assert.equal(usd.holdingsValueMinor, 300);
    assert.equal(usd.gainLossMinor, 100);
    assert.equal(mixed.accounts.find(a => a.id === card.id).totalValueMinor, -2000);
    assert.deepEqual((await service.getPortfolioSummary('other')).totalsByCurrency, []);
});
