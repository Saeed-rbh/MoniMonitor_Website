const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'moni-earned-income-'));
process.env.MONIMONITOR_DB_PATH=path.join(directory,'test.sqlite');
const service=require('../database/dbService');
const {buildMonthlyAnalysis}=require('./monthlyInsightService');
const {buildCashFlowWidgetPayload}=require('./cashFlowWidgetService');
let db;
const user='earned-income';
test.before(async()=>{db=await service.getDb();await service.createUser(user,user,'unused');});
test.after(async()=>{await db.close();fs.rmSync(directory,{recursive:true,force:true});});
test('income summaries, detail filters, AI facts and widget include 101.35 interest exactly once without rewriting history',async()=>{
 const base={userId:user,Timestamp:'2026-11-01T12:00:00.000Z',Currency:'CAD',Category:'Investment',PostingStatus:'posted',AccountFlow:'IN'};
 const deposit=await service.addTransaction({...base,Amount:32,Category:'Income',Label:'Personal Transfers Received'});
 const small=await service.addTransaction({...base,Amount:0.22,Category:'Income',Label:'Other Income'});
 const interest=await service.addTransaction({...base,Amount:101.35,PortfolioAction:'INTEREST',Label:'Investment Interest'});
 const dividend=await service.addTransaction({...base,Amount:5,Timestamp:'2026-10-01',PortfolioAction:'DIVIDEND',Label:'Dividends'});
 for(const fields of [{Amount:1000,PortfolioAction:'SELL'}, {Amount:500,PortfolioAction:'TRANSFER'}, {Amount:100,PortfolioAction:'INTEREST',AccountFlow:'NONE'}, {Amount:999,PortfolioAction:'DIVIDEND',PostingStatus:'pending'}, {Amount:100,PortfolioAction:'INTEREST',Currency:'USD'}])await service.addTransaction({...base,...fields});
 const before=await db.all('SELECT * FROM transactions ORDER BY id');
 const cashBefore=await db.all('SELECT * FROM account_balance_events');
 const holdingsBefore=await db.all('SELECT * FROM investment_holdings');
 // Simulate a persisted pre-fix cache, then exercise the same rebuild migration as production.
 await db.run("UPDATE monthly_transaction_summaries SET incomeMinor=3222 WHERE userId=? AND month='2026-11'",[user]);
 await require('../database/migrations').MIGRATIONS.find(m=>m.version===20).up(db);
 const summary=await service.getSummaryForUser(user);
 assert.equal(summary.byMonth.find(m=>m.month==='2026-11').income,133.57);
 assert.equal(summary.byMonth.find(m=>m.month==='2026-10').income,5);
 assert.equal(summary.totalIncome,138.57);
 assert.equal(summary.byLabel.find(l=>l.Label==='Investment Interest'&&l.Category==='Income').total,101.35);
 const filtered=await service.getAllTransactionsForUser(user,{category:'Income',from:'2026-11-01',to:'2026-11-30'});
 assert.deepEqual(filtered.filter(t=>t.Currency==='CAD').map(t=>t.id).sort((a,b)=>a-b),[deposit,small,interest]);
 assert.equal((await service.getAllTransactionsForUser(user,{category:'Income',limit:1,page:2})).length,1);
 const rows=await service.getAllTransactionsForUser(user);
 assert.equal(buildMonthlyAnalysis(rows,'2026-11').summary.incomeMinor,13357);
 assert.equal(buildCashFlowWidgetPayload(rows,{accounts:[]},new Date(2026,10,2)).totalIncome,133.57);
 assert.deepEqual(await db.all('SELECT * FROM transactions ORDER BY id'),before);
 assert.deepEqual(await db.all('SELECT * FROM account_balance_events'),cashBefore);
 assert.deepEqual(await db.all('SELECT * FROM investment_holdings'),holdingsBefore);
 assert.equal((await service.getTransactionById(interest,user)).Category,'Investment');
 assert.equal((await service.getTransactionById(dividend,user)).PortfolioAction,'DIVIDEND');
});
